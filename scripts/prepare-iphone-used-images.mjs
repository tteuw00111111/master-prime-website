// Prepare owner-supplied model/color reference images without changing the phones.
// Usage: node scripts/prepare-iphone-used-images.mjs [/path/to/iphone_promotional_images]
import sharp from 'sharp'
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { join } from 'node:path'
import { removeConnectedIPhoneMatte } from './lib/iphone-background-mask.mjs'
const source = process.argv[2] || '/home/wayne/Downloads/iphone_promotional_images'
const output = 'src/assets/images/iphone/apple-used'
const manifest = JSON.parse(await readFile(join(source, 'manifest.json'), 'utf8'))
const inventory = JSON.parse(await readFile(join(source, 'inventory.json'), 'utf8'))
const finishes = {
  black: ['Preto', '#303236'], midnight: ['Meia-noite', '#252c35'], starlight: ['Estelar', '#f1eee5'],
  blue: ['Azul', '#91acbf'], green: ['Verde', '#63796a'], pink: ['Rosa', '#e8c8ce'], red: ['Vermelho', '#bc253c'],
  gold: ['Dourado', '#ded0b4'], graphite: ['Grafite', '#545553'], silver: ['Prateado', '#e0e0db'],
  purple: ['Roxo', '#c3bdd7'], yellow: ['Amarelo', '#e9d87d'], deeppurple: ['Roxo-profundo', '#665d72'], spaceblack: ['Preto-espacial', '#454441'],
  blacktitanium: ['Titânio preto', '#4b4b49'], bluetitanium: ['Titânio azul', '#505968'], naturaltitanium: ['Titânio natural', '#a5a198'], whitetitanium: ['Titânio branco', '#dbd8d0'], deserttitanium: ['Titânio deserto', '#c4aa93'],
  teal: ['Verde-acinzentado', '#86aaa3'], ultramarine: ['Ultramarino', '#717cca'], white: ['Branco', '#ededea'],
}
const hash = data => createHash('sha256').update(data).digest('hex')
const models = {}, images = {}, records = [], processed = new Map()
await mkdir(output, { recursive: true })
for (const item of inventory) {
  const modelId = item.model.toLowerCase().replaceAll(' ', '-')
  const folder = join(source, item.folder, 'product-colors')
  const modelColors = []
  for (const filename of (await readdir(folder)).filter(f => f.endsWith('.png')).sort()) {
    const rawId = filename.slice(modelId.length + 1, -4)
    const id = ['product-red', 'productred'].includes(rawId) ? 'red' : rawId
    if (!finishes[id]) throw Error(`Unknown finish ${filename}`)
    const [name, swatch] = finishes[id]
    const path = `${item.folder}/product-colors/${filename}`
    const entry = manifest.find(row => row.path === path)
    if (!entry) throw Error(`No provenance for ${path}`)
    const input = await readFile(join(source, path))
    const inputHash = hash(input)
    if (inputHash !== entry.sha256) throw Error(`Checksum mismatch: ${path}`)
    const target = `${output}/${modelId}-${id}.webp`
    if (processed.has(target)) {
      if (processed.get(target) !== inputHash) throw Error(`Capacity-specific images differ: ${path}`)
    } else {
      // Crop the source padding, then mask only the edge-connected bright matte.
      // Preserve the handset RGB pixels and encode losslessly, including alpha.
      const first = await sharp(input).trim().toBuffer()
      const trimmed = await sharp(first).trim().toBuffer()
      const { data: pixels, info } = await sharp(trimmed).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
      const masked = removeConnectedIPhoneMatte(pixels, info.width, info.height)
      const result = await sharp(masked.pixels, { raw: { width: info.width, height: info.height, channels: 4 } }).webp({ lossless: true }).toBuffer({ resolveWithObject: true })
      await writeFile(target, result.data)
      processed.set(target, inputHash)
      images[modelId] ||= {}
      images[modelId][id] = target
      records.push({ ...entry, source_directory: source, workspace_path: target, processing: 'Crop source padding; remove only edge-connected flat bright background with a deterministic alpha mask. Preserve original handset RGB pixels, dimensions and colors; no AI editing or recoloring. Lossless WebP with transparency.', background_mask: { background_rgb: masked.background, removed_pixels: masked.removedPixels }, output_width: result.info.width, output_height: result.info.height, output_bytes: result.data.length, output_sha256: hash(result.data) })
      console.log(`${modelId}/${id}: ${masked.removedPixels} background pixels masked`)
    }
    modelColors.push({ id, name, swatch })
  }
  models[modelId] = modelColors
}
await writeFile(output + '/sources.json', JSON.stringify(records, null, 2) + '\n')
await writeFile('src/data/iphone-used-colors.ts', `// Model finishes from the owner-supplied promotional package, not store inventory.\n// Generated by scripts/prepare-iphone-used-images.mjs; see apple-used/sources.json.\nexport interface IPhoneUsedColor { id: string; name: string; swatch: string }\nconst colors: Record<string, readonly IPhoneUsedColor[]> = ${JSON.stringify(models, null, 2)}\nexport const getIPhoneUsedColors = (modelId: string) => colors[modelId] ?? []\n`)
let index = 0
const imports = [], entries = []
for (const [modelId, colors] of Object.entries(images)) {
  const rows = []
  for (const [id, path] of Object.entries(colors)) {
    const variable = `image${index++}`
    imports.push(`import ${variable} from '@/${path.slice(4)}'`)
    rows.push(`    '${id}': ${variable},`)
  }
  entries.push(`  '${modelId}': {\n${rows.join('\n')}\n  },`)
}
await writeFile('src/data/iphone-used-product-images.ts', `${imports.join('\n')}\n\n// Promotional reference images; unit photos and availability are confirmed by attendants.\nexport const IPHONE_USED_PRODUCT_IMAGES: Record<string, Record<string, string>> = {\n${entries.join('\n')}\n}\n`)
console.log(`Prepared ${records.length} finish images for ${Object.keys(models).length} models; 15 Pro capacities share the same renders.`)
